#!/usr/bin/env node
// Writes www/js/config.js from environment variables, so the Atomic SDK setup
// values in www/js/index.js's setupAtomic() aren't hardcoded in source. The
// WebView can't read process.env at runtime, so this has to run before every
// build (CI does this in .circleci/config.yml's inject_atomic_token command).
//
// Env vars (all required, values from the Atomic Workbench):
//   ATOMIC_API_HOST             Configuration -> SDK -> API Host (eg. "https://999-1.client-api.atomic.io")
//   ATOMIC_API_KEY              Configuration -> SDK -> API keys (eg. "my-api-key")
//   ATOMIC_ENVIRONMENT_ID       Configuration -> Environment ID (eg. "AbC12de3")
//   ATOMIC_STREAM_CONTAINER_ID  Configuration -> SDK -> Stream containers -> ID (eg. "123abcde")

const fs = require('fs');
const path = require('path');

const REQUIRED_VARS = ['ATOMIC_API_HOST', 'ATOMIC_API_KEY', 'ATOMIC_ENVIRONMENT_ID', 'ATOMIC_STREAM_CONTAINER_ID'];

const configJsPath = path.join(__dirname, '..', 'www', 'js', 'config.js');

const missing = REQUIRED_VARS.filter((name) => !process.env[name]);

if (missing.length > 0) {
  console.error(`Missing required environment variable(s): ${missing.join(', ')}.`);
  console.error('Set them to the values from the Atomic Workbench, then re-run.');
  process.exit(1);
}

const config = Object.fromEntries(REQUIRED_VARS.map((name) => [name, process.env[name]]));

fs.writeFileSync(
  configJsPath,
  `// Generated by scripts/generate-config.js - do not edit or commit.\nwindow.ATOMIC_CONFIG = ${JSON.stringify(config, null, 2)};\n`
);

console.log(`Wrote ${path.relative(process.cwd(), configJsPath)}.`);
